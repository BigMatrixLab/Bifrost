"""Draws the Bifrost cube mark as SVG.

The mark is an isometric cube cut into six interlocking strokes, the same
shape on each face turned 120 degrees. Everything is computed here so the
files stay exactly symmetric; run `python src-tauri/icons/bifrost-mark.py`
from the repository root after changing it, then `generate.ps1`.
"""
import math, os

C30 = math.cos(math.pi / 6)


def rot(p, deg):
    a = math.radians(deg)
    return (p[0] * math.cos(a) - p[1] * math.sin(a), p[0] * math.sin(a) + p[1] * math.cos(a))


def cube(R=133.4, w=21.5, g=10.5, lp=0.525, lq=0.40):
    """Polygons around (0, 0). R: hexagon radius, w: stroke, g: gap between faces."""
    T, a, b = (0, -R), (-R * C30, R / 2), (R * C30, R / 2)
    du, u1 = w / (R * C30), 1 - (g / 2) / (R * C30)
    P = lambda u, v: (T[0] + u * a[0] + v * b[0], T[1] + u * a[1] + v * b[1])
    outer = [(0, 0), (u1, 0), (u1, du), (du, du), (du, lp), (0, lp)]
    inner = [(0, u1), (u1, u1), (u1, lq), (u1 - du, lq), (u1 - du, u1 - du), (0, u1 - du)]
    face = [[P(*q) for q in outer], [P(*q) for q in inner]]
    return [[rot(p, 120 * k) for p in poly] for k in range(3) for poly in face]


def paths(polys, size=100.0, pad=0.0, R=133.4):
    s = (size - 2 * pad) / (2 * R)
    n = lambda v: f"{v:.2f}".rstrip("0").rstrip(".")
    return "".join(
        '<path d="M' + " L".join(f"{n(size / 2 + x * s)},{n(size / 2 + y * s)}" for x, y in poly) + 'Z"/>'
        for poly in polys
    )


def mark(fill="#4ade80", bold=False):
    polys = cube(w=27, g=13) if bold else cube()
    return f'<g fill="{fill}">{paths(polys)}</g>'


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.normpath(os.path.join(here, "..", ".."))
    svg = lambda body, extra="": (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="512" height="512"{extra}>{body}</svg>\n'
    )
    green = svg(mark())
    for p in ("src-tauri/icons/bifrost-mark-green.svg", "src/assets/bifrost-mark.svg", "website/assets/bifrost-mark.svg"):
        open(os.path.join(root, p), "w", newline="\n").write(green)
    # App icons: the mark on a transparent background, no plate.
    open(os.path.join(here, "app-icon.svg"), "w", newline="\n").write(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">\n'
        "  <!-- App icon: the Bifrost cube mark on a transparent background. -->\n"
        f'  <svg x="40" y="40" width="944" height="944" viewBox="0 0 100 100">{mark()}</svg>\n</svg>\n'
    )
    open(os.path.join(here, "app-icon-small.svg"), "w", newline="\n").write(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="256" height="256">\n'
        "  <!-- App icon for 16 to 48 px (taskbar, title bar, tray, Explorer): the cube\n"
        "       mark with thicker strokes and wider gaps so the cuts stay readable. -->\n"
        f'  <svg x="1" y="1" width="98" height="98" viewBox="0 0 100 100">{mark(bold=True)}</svg>\n</svg>\n'
    )
    open(os.path.join(here, "android-foreground.svg"), "w", newline="\n").write(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">\n'
        "  <!-- Android adaptive-icon foreground: the mark alone, inside the launcher's safe zone. -->\n"
        f'  <svg x="232" y="232" width="560" height="560" viewBox="0 0 100 100">{mark()}</svg>\n</svg>\n'
    )
    # Android status-bar icon for the transfer notification: white on transparent,
    # as Android requires (the system tints it).
    d = "".join(x.split('d="')[1].split('"')[0] for x in paths(cube(w=27, g=13)).split("<path")[1:])
    res = os.path.join(root, "plugins/bifrost-android/android/src/main/res/drawable")
    os.makedirs(res, exist_ok=True)
    open(os.path.join(res, "ic_stat_bifrost.xml"), "w", newline="\n").write(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Bifrost cube mark for the notification bar. Generated by src-tauri/icons/bifrost-mark.py. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp" android:height="24dp"\n'
        '    android:viewportWidth="100" android:viewportHeight="100">\n'
        f'  <path android:fillColor="#FFFFFFFF" android:pathData="{d}"/>\n'
        "</vector>\n"
    )
    print("written")
